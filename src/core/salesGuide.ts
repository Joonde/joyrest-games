/**
 * «Инструкция менеджера по продажам» (`/studio/sales-guide`; решение владельца 15 октября 2026). Как менеджер с ролью
 * `sales` ведёт клиента: от появления анкеты до проведённого мероприятия, и как он сам и владелец проверяют работу.
 * Текст в «…» показывается плашкой кнопки (как в «Как проводить игры»). Меняются условия, цены или экраны —
 * в том же PR правится этот файл.
 */

export interface SalesStep {
  /** Короткое действие. */
  title: string;
  /** Как именно (кнопки — в «…»). */
  text: string;
}

export interface SalesSection {
  id: string;
  title: string;
  /** Зачем этот этап, одной строкой. */
  lead?: string;
  /** Нумерованные шаги. */
  steps?: SalesStep[];
  /** Пункты-галочки: что проверить. */
  checks?: string[];
  /** Готовый текст для клиента (менеджер копирует и правит под себя). */
  template?: { title: string; text: string };
  /** Важное замечание. */
  note?: string;
}

