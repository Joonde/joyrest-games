-- «Кто хочет стать миллионером» → «Миллион на кону», «Своя игра» → «Ставка на знания», «100 к 1» → «Что скажет
-- большинство», «Угадай мелодию» → «Узнай по нотам», «Just Dance на поле» → «Танцуй как звезда», «Бункер» → «Убежище»,
-- «Перудо» → «Кости лжеца». Меняется только название игр библиотеки; личные игры ведущих и история не трогаются.
update games set title = replace(replace(replace(replace(replace(replace(replace(replace(replace(title,
    'Кто хочет стать миллионером?', 'Миллион на кону'),
    'Кто хочет стать миллионером', 'Миллион на кону'),
    'Миллионер', 'Миллион на кону'),
    'Своя игра', 'Ставка на знания'),
    '100 к 1', 'Что скажет большинство'),
    'Угадай мелодию', 'Узнай по нотам'),
    'Just Dance на поле', 'Танцуй как звезда'),
    'Бункер', 'Убежище'),
    'Перудо', 'Кости лжеца')
where scope = 'agency'
  and (title like '%миллионером%' or title like '%Миллионер%' or title like '%Своя игра%' or title like '%100 к 1%'
    or title like '%Угадай мелодию%' or title like '%Just Dance%' or title like '%Бункер%' or title like '%Перудо%');
