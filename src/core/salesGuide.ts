/**
 * Первое сообщение клиенту (решение владельца 15 октября 2026: попросить прислать набор из калькулятора сайта, чтобы
 * менеджер видел, что выбрал клиент). Кнопка «Скопировать первое сообщение» в «Клиентах» подставляет имена сама.
 */
export const FIRST_MESSAGE =
  "Здравствуйте, [имя]! Это [ваше имя], агентство праздников JoyRest. Вы оставили заявку на [повод]. Чтобы подобрать программу и точную цену, подскажите, пожалуйста: дату и время, сколько будет гостей и где пройдёт праздник? " +
  "И пришлите, пожалуйста, ваш расчёт из калькулятора на сайте joy-rest.ru — скриншот итога или текст: соберите там пакет, гостей и допы, как вам нравится. Так я сразу увижу, что вы выбрали. Удобно созвониться на 5 минут?";

/** Первое сообщение для конкретного клиента: подставлены его имя, имя менеджера и повод (если известны). */
export function firstMessage(client: string, manager: string, occasion: string): string {
  const name = client.trim();
  return (name ? FIRST_MESSAGE.replace("[имя]", name) : FIRST_MESSAGE.replace(", [имя]!", "!"))
    .replace("[ваше имя]", manager.trim() || "[ваше имя]")
    .replace("[повод]", occasion.trim() ? occasion.trim().toLowerCase() : "праздник");
}

