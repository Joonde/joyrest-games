const AGE_WORDS = (n: number) => (n % 10 === 1 && n % 100 !== 11 ? "год" : n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 10 || n % 100 >= 20) ? "года" : "лет");

export const ageText = (n: number) => `${n} ${AGE_WORDS(n)}`;

/** Текст карты по ссылке; неизвестная ссылка — «?». */
export function cardText(ref: string | null | undefined): string {
  if (!ref) return "?";
  const [kind, a, b] = ref.split(":");
  const i = Number(a);
  switch (kind) {
    case "p": {
      const name = PROFESSIONS[i];
      const years = Number(b);
      return name ? (years > 0 ? `${name} · стаж ${ageText(years)}` : name) : "?";
    }
    case "b": {
      const age = Number(b);
      return a === "m" || a === "f" ? `${a === "m" ? "Мужчина" : "Женщина"}, ${ageText(age)}` : "?";
    }
    case "h":
      return HEALTH[i]?.text ?? "?";
    case "y":
      return HOBBIES[i] ?? "?";
    case "g":
      return BAGGAGE[i] ?? "?";
    case "f":
      return FACTS[i] ?? "?";
    default:
      return "?";
  }
}

/** Пол и возраст из ссылки биологии. */
export function biologyOf(ref: string | null | undefined): { sex: Sex; age: number } | null {
  const [kind, sex, age] = (ref ?? "").split(":");
  return kind === "b" && (sex === "m" || sex === "f") && Number(age) >= 1 ? { sex, age: Number(age) } : null;
}

export function healthOf(ref: string | null | undefined): { infertile: boolean; healthy: boolean } {
  const [kind, a] = (ref ?? "").split(":");
  const card = kind === "h" ? HEALTH[Number(a)] : undefined;
  return { infertile: card?.infertile === true, healthy: kind === "h" && Number(a) === 0 };
}

/** Правильная ли ссылка на карту своей категории. */
export function isRef(cat: Cat, ref: unknown): ref is string {
  if (typeof ref !== "string" || ref.length > 16) return false;
  const [kind, a, b] = ref.split(":");
  const i = Number(a);
  switch (cat) {
    case "profession":
      return kind === "p" && Number.isInteger(i) && i >= 0 && i < PROFESSIONS.length && Number.isInteger(Number(b));
    case "biology":
      return biologyOf(ref) !== null;
    case "health":
      return kind === "h" && Number.isInteger(i) && i >= 0 && i < HEALTH.length;
    case "hobby":
      return kind === "y" && Number.isInteger(i) && i >= 0 && i < HOBBIES.length;
    case "baggage":
      return kind === "g" && Number.isInteger(i) && i >= 0 && i < BAGGAGE.length;
    case "fact":
      return kind === "f" && Number.isInteger(i) && i >= 0 && i < FACTS.length;
  }
}

const PREFIX: Record<Exclude<Cat, "biology" | "profession">, string> = { health: "h", hobby: "y", baggage: "g", fact: "f" };
const SIZE: Record<Exclude<Cat, "biology" | "profession">, number> = { health: HEALTH.length, hobby: HOBBIES.length, baggage: BAGGAGE.length, fact: FACTS.length };

/** Новая карта категории, которой ещё нет у игроков (`taken` — уже розданные ссылки). */
export function drawRef(cat: Cat, taken: Set<string>, random: () => number): string {
  const pick = (n: number) => Math.floor(random() * n);
  if (cat === "biology") return `b:${random() < 0.5 ? "m" : "f"}:${18 + pick(63)}`;
  if (cat === "profession") {
    const free = PROFESSIONS.map((_, i) => i).filter((i) => ![...taken].some((t) => t.startsWith(`p:${i}:`)));
    const i = free.length > 0 ? (free[pick(free.length)] as number) : pick(PROFESSIONS.length);
    return `p:${i}:${pick(25)}`;
  }
  const prefix = PREFIX[cat];
  const size = SIZE[cat];
  // «Полностью здоров» выпадает реже: остальное здоровье интереснее для споров.
  const all = Array.from({ length: size }, (_, i) => `${prefix}:${i}`).filter((r) => !taken.has(r) && !(cat === "health" && r === "h:0" && random() < 0.6));
  return all.length > 0 ? (all[pick(all.length)] as string) : `${prefix}:${pick(size)}`;
}
