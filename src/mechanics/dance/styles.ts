export function styleById(id: string): DanceStyle | null {
  return DANCE_STYLES.find((s) => s.id === id) ?? null;
}

export function isStyleId(value: unknown): value is string {
  return typeof value === "string" && DANCE_STYLES.some((s) => s.id === value);
}

/** Главный стиль игры: тот, что чаще всего у карточек (нет стилей — null). Нужен «Готовым программам». */
export function mainStyle(cards: Array<{ style: string }>): string | null {
  const counts = new Map<string, number>();
  for (const c of cards) if (c.style) counts.set(c.style, (counts.get(c.style) ?? 0) + 1);
  let best: string | null = null;
  let max = 0;
  for (const [id, n] of counts) if (n > max) [best, max] = [id, n];
  return best;
}
