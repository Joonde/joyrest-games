def sitemap() -> str:
    urls = [("", "1.0"), ("calc/", "0.8")] + [(f"{p['slug']}/", "0.9") for p in PAGES]
    body = "\n".join(
        f"  <url><loc>{ORIGIN}/{path}</loc><lastmod>{LASTMOD}</lastmod><priority>{prio}</priority></url>"
        for path, prio in urls
    )
    return f'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n{body}\n</urlset>\n'


def main() -> None:
    assert [p["slug"] for p in PAGES] == [s for s, _ in LINKS], "LINKS и PAGES — в одном порядке"
    for p in PAGES:
        out = SITE / p["slug"] / "index.html"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(page(p), encoding="utf-8")
    (SITE / "sitemap.xml").write_text(sitemap(), encoding="utf-8")
    print(f"Страниц услуг: {len(PAGES)}, sitemap.xml — {len(PAGES) + 2} адресов")


if __name__ == "__main__":
    main()
