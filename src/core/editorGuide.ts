export interface EditorStep {
  title: string;
  text: string;
}

export interface EditorField {
  /** Название поля или кнопки конструктора, как на экране. */
  name: string;
  /** Что это и на что влияет в игре. */
  text: string;
}

export interface EditorExample {
  title: string;
  /** Что ведущий делает в конструкторе. */
  setup: string;
  /** Что на экране зала во время игры. */
  hall: string;
  /** Что на телефонах гостей. */
  phones: string;
  /** Что на пульте. */
  host?: string;
}

export interface EditorGuide {
  /** id механики (`src/mechanics/registry.ts`). */
  mechanic: string;
  title: string;
  icon: string;
  summary: string;
  start: string[];
  steps: EditorStep[];
  fields: EditorField[];
  examples: EditorExample[];
  /** Почему «▶ Запустить игру» может быть неактивна. */
  ready: string[];
  tips: string[];
}

/** Общий раздел инструкции: пункты, схема-стрелки и примеры. */
export interface EditorBasics {
  id: string;
  icon: string;
  title: string;
  /** Схема: шаги слева направо (на телефоне — сверху вниз). */
  flow?: Array<{ title: string; text: string }>;
  items: string[];
  examples?: EditorExample[];
}

