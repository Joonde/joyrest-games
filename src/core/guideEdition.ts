// Инструкции «Как проводить игры» и «Как создавать игры» для JoyRest Лайт (решение владельца 23 октября 2026).
// Тексты общие с платформой агентства: правки в guide.ts и editorGuide/ попадают в Лайт сами. Здесь — только то, чего
// в Лайте нет (фотоотчёт, чаевые, отзывы, Авито, Telegram, календарь, «Оформление под заказчика», предложения в
// библиотеку, роли «владелец и заместитель») и адрес платформы. Тест `guideEdition.test.ts` проверяет, что каждое
// правило ещё находит свой текст (поменяли текст в main — тест подскажет поправить правило) и что в Лайте не осталось
// упоминаний скрытых разделов.

/** Правило: что найти и на что заменить; `null` — убрать пункт списка целиком. */
export type LiteRule = readonly [RegExp, string | null];

export const LITE_RULES: readonly LiteRule[] = [
  // Подготовка: папки «Игры от ведущих JoyRest» в Лайте нет — предложений в библиотеку нет.
  [/, в самом низу — «Игры от ведущих JoyRest» \([^)]*\)/, ""],
  // Запуск: «Оформление под заказчика» — платный «Фирменный шаблон», в Лайте его нет.
  [/; «Оформление под заказчика» — логотип и цвета компании или пары/, ""],
  // Пульт: фотоотчёта нет.
  [/ «📷 Общее фото для фотоотчёта»,/, ""],
  // Финал: «Спасибо» без QR чаевых, отзыва, Авито и канала.
  [
    /^«Завершить игру»\. Экран сам покажет «Спасибо» — до четырёх QR.*$/,
    "«Завершить игру». Экран сам покажет «Спасибо, что были с нами!», под ним — итоги. Убрать «Спасибо» и вернуть его — кнопкой на пульте: «Убрать «Спасибо» — показать итоги» / ««Спасибо» — на экран».",
  ],
  [/^Общее фото: «📷 Общее фото для фотоотчёта».*$/, null],
  [/ Отзывы гостей — в студии, «Отзывы»; фото — «Фотоотчёты»\./, ""],
  [/^Мероприятие из календаря закончилось.*$/, null],
  // Конструктор: предложений в библиотеку нет.
  [/, «Предложить в библиотеку»/, ""],
  [/^Игра получилась удачной — «⋯» → «Предложить в библиотеку».*$/, null],
  [/^Папки, копии и предложение в библиотеку$/, "Папки и копии"],
  [/игру агентства менять нельзя/, "игру библиотеки менять нельзя"],
  // Ролей команды агентства (владелец, заместитель) у подписчика нет.
  [/ \(владелец и заместитель в библиотеке\)/, ""],
  [/ролики, которые загрузили владелец и заместитель/, "ролики, загруженные в JoyRest"],
  [/ Владелец и заместитель (?:могут|видят)[^.]*\./, ""],
];

/**
 * Разделы целиком, которых в Лайте нет (заголовок блока): «Заявка от менеджера» — планировщик и Telegram агентства
 * (решение владельца 30 октября 2026: в Лайте ведущий сам себе менеджер, календаря и бота нет).
 */
export const LITE_DROP_BLOCKS: readonly RegExp[] = [/^Заявка от менеджера/];

/** Адрес платформы в текстах агентства. */
const AGENCY_HOST = /games\.joy-rest\.ru/g;

/** Текст для Лайта: правила по порядку, адрес — свой. `null` — убрать пункт. */
export function liteText(text: string, host: string): string | null {
  let out = text;
  for (const [find, to] of LITE_RULES) {
    if (!find.test(out)) continue;
    if (to === null) return null;
    out = out.replace(find, to);
  }
  return out.replace(AGENCY_HOST, host);
}

function droppedBlock(item: unknown): boolean {
  if (!item || typeof item !== "object" || Array.isArray(item)) return false;
  const title = (item as { title?: unknown }).title;
  return typeof title === "string" && LITE_DROP_BLOCKS.some((r) => r.test(title));
}

/** Копия данных инструкции для Лайта: все строки через `liteText`, убранные пункты списков выпадают. */
export function forLite<T>(data: T, host: string): T {
  const walk = (v: unknown): unknown => {
    if (typeof v === "string") return liteText(v, host) ?? "";
    if (Array.isArray(v)) {
      const out: unknown[] = [];
      for (const item of v) {
        if (droppedBlock(item)) continue;
        if (typeof item === "string") {
          const t = liteText(item, host);
          if (t !== null) out.push(t);
        } else out.push(walk(item));
      }
      return out;
    }
    if (v && typeof v === "object") {
      return Object.fromEntries(Object.entries(v as Record<string, unknown>).map(([k, x]) => [k, walk(x)]));
    }
    return v;
  };
  return walk(data) as T;
}
