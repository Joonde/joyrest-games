// Шаблоны «100 к 1» для «Библиотеки JoyRest»: свадьба, корпоратив, день рождения и общий набор для «Весь зал».
// Вопросы придуманы JoyRest (не из телепередачи), очки — ОЦЕНКА JoyRest, а не опрос: `source: "estimate"`, и на
// экране, пульте и в конструкторе так и подписано. Настоящие проценты даёт «Опрос гостей заранее».
import { ROUND_KINDS, type HundredContent, type HundredMode, type HundredQuestion, type HundredRound, type RoundKind } from "./content";

/** Ответ: текст, очки, синонимы через запятую. */
type A = [string, number, string?];
type Q = [string, A[]];

function question(prefix: string, n: number, [text, answers]: Q): HundredQuestion {
  return {
    id: `${prefix}q${n}`,
    text,
    source: "estimate",
    pollCount: 0,
    answers: answers.map(([t, points, syn], i) => ({
      id: `${prefix}q${n}a${i + 1}`,
      text: t,
      points,
      synonyms: (syn ?? "")
        .split(",")
        .map((s) => s.trim())
        .filter(Boolean),
    })),
  };
}

/** Четыре обычных раунда (простая, двойная, тройная, наоборот) и «Большая игра» из пяти вопросов. */
function game(prefix: string, mode: HundredMode, normal: [Q, Q, Q, Q], big: [Q, Q, Q, Q, Q]): HundredContent {
  let n = 0;
  const rounds: HundredRound[] = ROUND_KINDS.map((kind: RoundKind, i) => ({
    id: `${prefix}r${i + 1}`,
    kind,
    questions: kind === "big" ? big.map((q) => question(prefix, ++n, q)) : [question(prefix, ++n, normal[i] ?? normal[0])],
  }));
  return { mode, rounds, buzzTime: 10, hallTime: 60, bigTimes: [20, 25], bigGoal: 200, bigBonus: 100, look: "studio", pollId: null };
}

