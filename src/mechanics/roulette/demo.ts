type Extra = {
  options?: string[];
  correct?: number[];
  answers?: string[];
  numberAnswer?: number;
  unit?: string;
  seconds?: number;
  adult?: boolean;
  alcohol?: boolean;
  sport?: boolean;
  alt?: string;
  note?: string;
  effect?: BonusEffect;
  rate?: "host" | "captains";
  judge?: "host" | "captains" | "hall";
  opponent?: "captain" | "host" | "random";
};

const POINTS: Record<Rarity, number> = { common: 50, rare: 100, legendary: 200 };

function t(id: string, kind: TaskKind, rarity: Rarity, title: string, text: string, extra: Extra = {}): Record<string, unknown> {
  return { id, kind, rarity, title, text, points: POINTS[rarity], ...extra };
}

function theme(id: string, name: string, short: string, icon: ThemeIcon, tasks: Array<Record<string, unknown>>): Record<string, unknown> {
  return { id, name, short, icon, active: true, tasks };
}

