/** Памятка на случай игры, для которой текста нет. */
export const BLOCK_PREP_DEFAULT = "Откройте игру и проверьте вопросы и задания под эту компанию.";

export function blockPrepOf(mechanic: string): string {
  return BLOCK_PREP[mechanic] ?? BLOCK_PREP_DEFAULT;
}

/** Номера блоков (с 1), где в личном вечере стоит игра библиотеки — со стандартными вопросами. */
export function templateBlocks(eveningScope: "agency" | "personal", blockScopes: Array<"agency" | "personal" | null>): number[] {
  if (eveningScope !== "personal") return [];
  return blockScopes.flatMap((scope, i) => (scope === "agency" ? [i + 1] : []));
}

/** «Блок 2» / «Блоки 1 и 3» / «Блоки 1, 2 и 4». */
export function blocksLabel(numbers: number[]): string {
  if (numbers.length === 0) return "";
  if (numbers.length === 1) return `Блок ${numbers[0]}`;
  const head = numbers.slice(0, -1).join(", ");
  return `Блоки ${head},  ${numbers[numbers.length - 1]}`;
}

/** Предупреждение перед запуском личного вечера, где остались шаблоны библиотеки. null — всё своё. */
export function prepWarning(numbers: number[]): string | null {
  if (numbers.length === 0) return null;
  const many = numbers.length > 1;
  return `${blocksLabel(numbers)} — ${many ? "шаблоны" : "шаблон"} библиотеки: вопросы и задания стандартные, не под эту компанию.`;
}

/** Название копии игры для вечера: «Квиз · для вечера «Юбилей Анны»» (не длиннее `max`). */
export function prepTitle(gameTitle: string, eveningTitle: string, max: number): string {
  const evening = eveningTitle.trim();
  if (!evening) return gameTitle.slice(0, max);
  const tail = ` · для вечера «${evening}»`;
  if (gameTitle.length + tail.length <= max) return gameTitle + tail;
  const shortTail = " · для вечера";
  return gameTitle.slice(0, Math.max(1, max - shortTail.length)) + shortTail;
}
