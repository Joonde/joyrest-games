/**
 * Роль только добавляет: ведущий с ролью остаётся ведущим со всеми своими правами (игры, музыка,
 * сессии), роль открывает ему ещё один раздел. Роль у человека одна; дать её может только владелец.
 */
export type AccessRole = (typeof ACCESS_ROLES)[number]["id"];

export function isAccessRole(value: unknown): value is AccessRole {
  return typeof value === "string" && ACCESS_ROLES.some((r) => r.id === value);
}

export function accessRoleTitle(value: unknown): string | null {
  return ACCESS_ROLES.find((r) => r.id === value)?.title ?? null;
}
