const who = (mode: Mode) => (mode === "teams" ? "капитан команды" : "каждый со своего телефона");

const RULES: Record<string, (mode: Mode) => RulesText> = {
  quiz: (mode) => ({
    title: "Правила квиза",
    lines: [
      "Вопросы — на экране, отвечает " + who(mode),
      "Чем быстрее верный ответ, тем больше очков",
      "Ответ отправлен — изменить нельзя",
      "После каждого ответа — таблица и кто вырвался вперёд",
      "Подсказывать соседям можно, но тихо",
      "Ведущий всегда прав",
    ],
  }),
  lotto: (mode) => ({
    title: "Правила музыкального лото",
    lines: [
      mode === "teams" ? "У каждой команды — своя карточка с песнями" : "У каждого — своя карточка с песнями на телефоне",
      "Звучит песня — нашли её у себя? Отметьте",
      "Собрали линию — жмите «Лото!»",
      "Ведущий проверит карточку: ошибка — штраф",
      "Кто первым собрал — забирает приз",
    ],
  }),
  board: (mode) => ({
    title: "Правила «Своей игры»",
    lines: [
      "На экране поле: темы и стоимость вопросов",
      mode === "teams" ? "Команда выбирает клетку, ведущий её открывает" : "Игрок выбирает клетку, ведущий её открывает",
      "Знаете ответ — жмите кнопку на телефоне первыми",
      "Верно — очки клетки и право выбора",
      "Неверно — слово переходит следующему",
      "«Кот в мешке»: ставка до всего своего счёта",
    ],
  }),
  checkers: () => ({
    title: "Правила «Шашек»",
    lines: [
      "Две команды: белые и чёрные",
      "Вопрос на экране — отвечает капитан",
      "Ход получает команда, ответившая верно и быстрее",
      "Ход делает капитан на своём телефоне",
      "Взяли шашку — 10 очков, дамку — 30",
      "Победа в партии — 50 очков, иначе решает счёт",
    ],
  }),
  dance: (mode) => ({
    title: "Правила танцевального батла",
    lines: [
      mode === "teams" ? "Команды выступают по очереди" : "Участники выступают по очереди",
      "Капитан выбирает карточку: батл, танец или караоке",
      "Выступление — на экране видео или музыка",
      "Остальные оценивают от 10 до 100 с телефонов",
      "Свою команду оценить нельзя",
      "В батле зал голосует за победителя",
    ],
  }),
  quest: () => ({
    title: "Правила «Активной настолки»",
    lines: [
      "Капитан бросает кубик на телефоне",
      "Фишка идёт по полю, на клетке — задание",
      "Выполнили — очки клетки, ведущий решает",
      "Бонус — вперёд, ловушка — назад, пропуск — ход соседу",
      "Кто первым на финише — получает приз",
    ],
  }),
};

const FALLBACK: RulesText = {
  title: "Правила игры",
  lines: ["Отвечайте с телефона — вопросы на экране", "Чем быстрее верный ответ, тем больше очков", "Подсказывать соседям можно, но тихо", "Ведущий всегда прав"],
};

export function rulesFor(mechanic: string | null | undefined, mode: Mode): RulesText {
  const make = mechanic ? RULES[mechanic] : undefined;
  return make ? make(mode) : FALLBACK;
}
