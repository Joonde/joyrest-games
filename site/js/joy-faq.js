  /** Нижний регистр, ё → е, без знаков препинания и лишних пробелов. */
  function normalize(s) {
    return ' ' + String(s || '').toLowerCase().replace(/ё/g, 'е').replace(/[^a-zа-я0-9]+/g, ' ').trim() + ' ';
  }

  /**
   * Подбор ответа. Ответ: { item, others } — item уверенный ответ или null, others — 2–3 похожих, если вопрос неясен.
   * Корень из keys совпадает с началом слова вопроса; балл шаблона — сумма длин совпавших корней (длинное совпадение
   * «сколько стоит» весомее «стоит»). Точное совпадение с текстом кнопки — сразу он.
   */
  function match(text, items) {
    var q = normalize(text);
    if (q.trim().length < 2) return { item: null, others: [] };
    var scored = [];
    items.forEach(function (it) {
      if (normalize(it.q) === q) { scored.push({ it: it, score: 1000 }); return; }
      var score = 0;
      it.keys.forEach(function (k) {
        var key = normalize(k).trim();
        if (key && q.indexOf(' ' + key) >= 0) score += key.length;
      });
      if (score > 0) scored.push({ it: it, score: score });
    });
    scored.sort(function (a, b) { return b.score - a.score; });
    if (!scored.length) return { item: null, others: [] };
    var best = scored[0];
    var close = scored.filter(function (s) { return s.score === best.score; });
    if (close.length === 1) return { item: best.it, others: [] };
    return { item: null, others: close.slice(0, 3).map(function (s) { return s.it; }) };
  }

