// «Как проводить игры» — инструкция для ведущих в студии (`/studio/guide`).
// ПРАВИЛО: меняется механика (кнопки пульта, что видят гости, очки, правила) — в том же PR правим её раздел здесь.
// Тест `guide.test.ts` проверяет, что у каждой механики из реестра есть раздел.
// В текстах «…» — названия кнопок и надписей: на странице они выделяются.

export interface GuideStep {
  title: string;
  text: string;
}

export interface GuideFlow {
  /** Что нажимает ведущий — по порядку. */
  host: GuideStep[];
  /** Что в этот момент на телефонах. */
  phones: GuideStep[];
  /** Повтор: с какого шага пульта (номер с 1) и подпись. */
  loop: { to: number; label: string };
  /** Чем заканчивается. */
  end: string;
}

export interface GuideTable {
  title: string;
  head: [string, string] | [string, string, string];
  rows: string[][];
}

export interface GameGuide {
  /** id механики (`src/mechanics/registry.ts`). */
  mechanic: string;
  title: string;
  icon: string;
  summary: string;
  flow: GuideFlow;
  host: string[];
  /** Пояснения после шагов ведущего (подсказки, особые клетки). */
  notes?: string[];
  players: string[];
  /** Как объяснить гостям за 20 секунд. */
  explain: string;
  tables?: GuideTable[];
}

