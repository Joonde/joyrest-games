function build(variant: StageVariant, rows: Row[]): StageContent {
  const categories = rows.map(([title], i) => ({ id: `c${i + 1}`, title }));
  const tiles = rows.flatMap(([, list], ci) =>
    list.map(([points, who, title, note], ti) => {
      const battle = who.startsWith("vs:");
      return { id: `t${ci + 1}_${ti + 1}`, cat: `c${ci + 1}`, points, kind: battle ? "battle" : "perform", who: battle ? "a2" : who, vs: battle ? who.slice(3) : "m-w", title, note, video: { source: "none", url: "", name: "" } };
    }),
  );
  return parseStage({ variant, categories, tiles, gift: 50, voteTime: 20 });
}

